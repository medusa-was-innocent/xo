function key(title: string) {
  return title
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/['’.]/g, "")
    .replace(/&/g, "and")
    .replace(/…/g, " ")
    .replace(/[^a-z0-9]+/g, " ")
    .replace(/\bpt\b/g, "part")
    .replace(/\s+/g, " ")
    .trim();
}

